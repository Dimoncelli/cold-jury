import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { after, describe, it } from 'node:test';
import { assertNotSymlink, capInput, helpText, hookScript, main, VERSION } from '../src/cli.js';

const tempDirs = [];

function tempDir(prefix = 'cold-jury-cli-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  tempDirs.push(dir);
  return dir;
}

function capture() {
  const chunks = [];
  return {
    write(value) {
      chunks.push(String(value));
      return true;
    },
    text() {
      return chunks.join('');
    },
  };
}

async function run(argv, options = {}) {
  const stdout = capture();
  const stderr = capture();
  const code = await main(argv, { stdout, stderr, ...options });
  return { code, stdout: stdout.text(), stderr: stderr.text() };
}

const REPORTS = [
  { engine: 'claude', status: 'READY', command: 'claude.exe', path: '/bin/claude.exe' },
  { engine: 'codex', status: 'NOT_FOUND', command: '', path: '' },
  { engine: 'gemini', status: 'NOT_FOUND', command: '', path: '' },
  { engine: 'opencode', status: 'READY', command: 'node', path: '/bin/opencode.cmd' },
  { engine: 'ollama', status: 'OFFLINE', command: 'ollama.exe', path: '/bin/ollama.exe' },
];

const fakeDoctor = () => REPORTS;

after(() => {
  for (const dir of tempDirs) fs.rmSync(dir, { recursive: true, force: true });
});

describe('cli: version and help', () => {
  it('prints the version and exits 0', async () => {
    for (const flag of ['--version', '-v']) {
      const result = await run([flag]);
      assert.equal(result.code, 0);
      assert.equal(result.stdout, `cold-jury ${VERSION}\n`);
      assert.equal(VERSION, '0.1.0');
    }
  });

  it('prints help with every subcommand and exits 0', async () => {
    for (const flag of ['--help', '-h']) {
      const result = await run([flag]);
      assert.equal(result.code, 0);
      for (const command of ['doctor', 'review', 'install-hook']) {
        assert.ok(result.stdout.includes(command));
      }
      assert.ok(result.stdout.includes('--fail-on'));
      assert.ok(result.stdout.includes('--max-bytes'));
      assert.ok(helpText().includes(VERSION));
    }
  });
});

describe('cli: doctor', () => {
  it('prints READY, OFFLINE and NOT_FOUND rows', async () => {
    const result = await run(['doctor', '--no-color'], { doctor: fakeDoctor });
    assert.equal(result.code, 0);
    assert.ok(result.stdout.includes('READY'));
    assert.ok(result.stdout.includes('OFFLINE'));
    assert.ok(result.stdout.includes('NOT_FOUND'));
    assert.ok(result.stdout.includes('/bin/claude.exe'));
    assert.equal(result.stdout.includes('\u001b['), false);
  });

  it('accepts --doctor as an alias', async () => {
    const result = await run(['--doctor', '--no-color'], { doctor: fakeDoctor });
    assert.equal(result.code, 0);
    assert.ok(result.stdout.includes('ENGINE'));
  });

  it('awaits an asynchronous doctor', async () => {
    const result = await run(['doctor', '--no-color'], { doctor: async () => REPORTS });
    assert.equal(result.code, 0);
    assert.ok(result.stdout.includes('OFFLINE'));
  });
});

describe('cli: install-hook', () => {
  it('refuses to run outside a git repository', async () => {
    const cwd = tempDir();
    const result = await run(['install-hook'], { cwd });
    assert.equal(result.code, 2);
    assert.match(result.stderr, /not_a_git_repo/);
  });

  it('installs a pre-push hook that reviews the pushed range', async () => {
    const cwd = tempDir();
    fs.mkdirSync(path.join(cwd, '.git'), { recursive: true });

    const first = await run(['install-hook'], { cwd });
    assert.equal(first.code, 0);
    const hookPath = path.join(cwd, '.git', 'hooks', 'pre-push');
    const installed = fs.readFileSync(hookPath, 'utf8');
    assert.ok(installed.startsWith('#!/bin/sh'));
    assert.ok(installed.includes('Generated by cold-jury'));
    assert.ok(installed.includes('while read -r local_ref local_sha remote_ref remote_sha'));
    assert.ok(installed.includes('--author hook --range'));
    assert.ok(installed.includes('remote_sha'));
    assert.ok(installed.includes('@{u}'));
    assert.ok(installed.includes('HEAD~1'));
    assert.equal(installed.includes('npx cold-jury'), false, 'no npm squatting surface');
    assert.ok(installed.includes('cold-jury.mjs'), 'uses the bundled binary by default');

    const second = await run(['install-hook'], { cwd });
    assert.equal(second.code, 0);
    assert.match(second.stdout, /already installed/);
    assert.equal(fs.readFileSync(hookPath, 'utf8'), installed);
  });

  it('supports a pre-commit hook', async () => {
    const cwd = tempDir();
    fs.mkdirSync(path.join(cwd, '.git'), { recursive: true });
    const result = await run(['install-hook', '--type', 'pre-commit'], { cwd });
    assert.equal(result.code, 0);
    const installed = fs.readFileSync(path.join(cwd, '.git', 'hooks', 'pre-commit'), 'utf8');
    assert.ok(installed.includes('--author hook --staged'));
  });

  it('does not overwrite a foreign hook without --force', async () => {
    const cwd = tempDir();
    fs.mkdirSync(path.join(cwd, '.git', 'hooks'), { recursive: true });
    const hookPath = path.join(cwd, '.git', 'hooks', 'pre-push');
    fs.writeFileSync(hookPath, '#!/bin/sh\necho custom\n');

    const blocked = await run(['install-hook'], { cwd });
    assert.equal(blocked.code, 2);
    assert.match(blocked.stderr, /hook_exists/);
    assert.equal(fs.readFileSync(hookPath, 'utf8'), '#!/bin/sh\necho custom\n');

    const forced = await run(['install-hook', '--force'], { cwd });
    assert.equal(forced.code, 0);
    assert.ok(fs.readFileSync(hookPath, 'utf8').includes('Generated by cold-jury'));
  });

  it('refuses a symlinked hook', async (t) => {
    const cwd = tempDir();
    const hooksDir = path.join(cwd, '.git', 'hooks');
    fs.mkdirSync(hooksDir, { recursive: true });
    const target = path.join(cwd, 'outside.sh');
    fs.writeFileSync(target, '#!/bin/sh\n');
    try {
      fs.symlinkSync(target, path.join(hooksDir, 'pre-push'));
    } catch {
      t.skip('symlinks need privileges on this host');
      return;
    }
    const result = await run(['install-hook'], { cwd });
    assert.equal(result.code, 2);
    assert.match(result.stderr, /symlink_refused/);
  });
});

describe('cli: input cap', () => {
  const LF = String.fromCharCode(10);
  const CRLF = String.fromCharCode(13, 10);

  it('keeps a LF diff under the cap untouched', () => {
    const text = ['diff --git a/app.js b/app.js', '+console.log(1)', ''].join(LF);
    const result = capInput(text, 1000);
    assert.equal(result.text, text);
    assert.equal(result.limit, null);
  });

  it('never leaves a dangling carriage return when truncating a CRLF diff', () => {
    const text = ['x'.repeat(70), 'y'.repeat(50)].join(CRLF);
    const result = capInput(text, 80);
    assert.equal(result.limit.truncated, true);
    assert.equal(result.limit.maxBytes, 80);
    assert.ok(result.limit.originalBytes > 80);
    assert.equal(result.text.endsWith(String.fromCharCode(13)), false);
    assert.equal(result.text, 'x'.repeat(70));
  });
});

describe('cli: symlink guard', () => {
  it('refuses a symlinked target and accepts a regular file or a missing one', () => {
    const symlinkFs = { lstatSync: () => ({ isSymbolicLink: () => true }) };
    assert.throws(
      () => assertNotSymlink('/repo/hook', 'symlink_refused', symlinkFs),
      (error) => error.code === 'symlink_refused' && error.exitCode === 2,
    );

    const regular = { lstatSync: () => ({ isSymbolicLink: () => false }) };
    assert.doesNotThrow(() => assertNotSymlink('/repo/hook', 'symlink_refused', regular));

    const missing = {
      lstatSync() {
        const error = new Error('ENOENT');
        error.code = 'ENOENT';
        throw error;
      },
    };
    assert.doesNotThrow(() => assertNotSymlink('/repo/hook', 'symlink_refused', missing));
  });
});

describe('cli: hook script generation', () => {
  it('falls back to the GitHub package when no local binary is used', () => {
    const script = hookScript('pre-push', 'npx --yes github:Dimoncelli/cold-jury');
    assert.ok(script.includes('npx --yes github:Dimoncelli/cold-jury review --author hook --range'));
    assert.equal(script.includes('npx cold-jury'), false);
  });
});

describe('cli: review guards', () => {
  it('rejects an unresolved author with exit 2', async () => {
    const result = await run(['review'], { env: {}, doctor: fakeDoctor, cwd: tempDir() });
    assert.equal(result.code, 2);
    assert.match(result.stderr, /author_not_detected/);
    assert.match(result.stderr, /--author hook/);
  });

  it('rejects unknown flags with exit 2', async () => {
    const result = await run(['review', '--nope']);
    assert.equal(result.code, 2);
    assert.match(result.stderr, /unknown_flag/);
  });

  it('rejects a git flag injection before running git', async () => {
    const result = await run(['review', '--author', 'claude', '--range=--output=/tmp/pwn']);
    assert.equal(result.code, 2);
    assert.match(result.stderr, /invalid_range/);
  });

  it('reports a git failure instead of crashing', async () => {
    const cwd = tempDir();
    const result = await run(['review', '--author', 'claude', '--json'], {
      cwd,
      env: {},
      doctor: fakeDoctor,
      resolveBinary: () => ({ command: 'git', prefixArgs: [], wrapper: 'direct' }),
    });
    assert.equal(result.code, 2);
    assert.match(result.stderr, /git_diff_failed|git_not_available/);
  });

  it('rejects an output path escaping the repository', async () => {
    const cwd = tempDir();
    const result = await run(['review', '--output', '../escape.json', '--author', 'claude'], { cwd, env: {}, doctor: fakeDoctor });
    assert.equal(result.code, 2);
    assert.match(result.stderr, /output_outside_cwd/);
  });
});
